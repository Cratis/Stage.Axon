#!/usr/bin/env node
// Regenerate from a rendered corpus application's Maven dependencies. Requires a JDK (25+).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { basename, delimiter, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const application = process.argv[2];
if (!application) throw new Error('Usage: node Source/Rendering.Axon.Verification/AnnotationAllowlist.regenerate.mjs <rendered-application-directory>');
const javap = process.env.JAVA_HOME ? join(process.env.JAVA_HOME, 'bin', 'javap') : 'javap';
const version = execFileSync(javap, ['-version'], { encoding: 'utf8' }).trim();
if (Number.parseInt(version, 10) < 25) throw new Error(`JDK 25+ required; javap is ${version}`);
const work = join(repository, '.ai-work', 'axon-s2');
mkdirSync(work, { recursive: true });
const classpathFile = join(work, 'annotation-classpath.txt');
execFileSync('sh', ['./mvnw', '-q', '-B', 'dependency:build-classpath', `-Dmdep.outputFile=${classpathFile}`, '-Dmdep.includeScope=test'], { cwd: resolve(application), stdio: 'inherit' });
const jars = [...new Set(readFileSync(classpathFile, 'utf8').trim().split(delimiter)
    .filter(path => /[/\\]org[/\\]axonframework[/\\].*[/\\]5\.4\.1[/\\]/.test(path)))].sort();
if (!jars.length) throw new Error('No org.axonframework jars resolved');
if (jars.some(path => !/[/\\]5\.4\.1[/\\]/.test(path))) throw new Error('Expected Axon 5.4.1 jars only');

// Read the ZIP central directory using only Node's standard library; no jar/unzip dependency.
function directory(bytes) {
    for (let end = bytes.length - 22; end >= Math.max(0, bytes.length - 65557); end--) {
        if (bytes.readUInt32LE(end) === 0x06054b50)
            return { count: bytes.readUInt16LE(end + 10), offset: bytes.readUInt32LE(end + 16) };
    }
    throw new Error('Invalid jar: end of central directory missing');
}

function isAxonClass(name) {
    if (!name.startsWith('org/axonframework/')) return false;
    if (!name.endsWith('.class')) return false;
    return !name.endsWith('package-info.class');
}

function classes(path) {
    const bytes = readFileSync(path);
    let { count, offset } = directory(bytes);
    const result = [];
    for (let entry = 0; entry < count; entry++) {
        if (bytes.readUInt32LE(offset) !== 0x02014b50) throw new Error(`Invalid central directory: ${path}`);
        const length = bytes.readUInt16LE(offset + 28);
        const name = bytes.toString('utf8', offset + 46, offset + 46 + length);
        if (isAxonClass(name))
            result.push(name.slice(0, -6).replaceAll('/', '.'));
        offset += 46 + length + bytes.readUInt16LE(offset + 30) + bytes.readUInt16LE(offset + 32);
    }
    return result;
}

const names = [...new Set(jars.flatMap(classes))].sort();
const annotations = new Set();
for (let index = 0; index < names.length; index += 100) {
    const output = execFileSync(javap, ['-classpath', jars.join(delimiter), ...names.slice(index, index + 100)], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
    for (const match of output.matchAll(/public\s+(?:@interface\s+([\w.$]+)|interface\s+([\w.$]+)\s+extends\s+java\.lang\.annotation\.Annotation)/g))
        annotations.add((match[1] ?? match[2]).replaceAll('$', '.'));
}
if (!annotations.size) throw new Error('javap found no annotations');
const output = join(repository, 'Source', 'Rendering.Axon.Verification', 'AnnotationAllowlist.txt');
const header = '# Generated by AnnotationAllowlist.regenerate.mjs from Axon Framework 5.4.1\n' +
    '# Scanned jars: ' + jars.map(path => basename(path)).join(', ') + '\n' +
    '# Regenerate when AxonMavenProject.cs changes the axon-framework-bom version or adds an Axon artifact.\n' +
    '# JAVA_HOME=<jdk-25-or-newer> node Source/Rendering.Axon.Verification/AnnotationAllowlist.regenerate.mjs <rendered-app>\n';
writeFileSync(output, header + [...annotations].sort().join('\n') + '\n');
console.log(`Recorded ${annotations.size} annotations from ${jars.length} Axon 5.4.1 jars in ${output}`);
